test('password reset uses generic responses, hashes, expiry, single use and session invalidation',async()=>{
  const {sendPasswordResetEmail}=require('../config/mailer');
  const session=await login(student),anonymous=http(app);
  const first=await anonymous.post('/forgot-password').type('form').send({email:student.email});
  const absent=await anonymous.post('/forgot-password').type('form').send({email:'absent@example.invalid'});
  expect([first.status,first.headers.location]).toEqual([absent.status,absent.headers.location]);
  const token=sendPasswordResetEmail.mock.calls.at(-1)[1];
  const stored=await db.one('SELECT reset_token_hash,reset_expires_at FROM users WHERE id=$1',[student.id]);
  expect(stored.reset_token_hash).toBe(hashToken(token));expect(stored.reset_token_hash).not.toBe(token);
  await db.none("UPDATE users SET reset_expires_at=NOW()-INTERVAL '1 second' WHERE id=$1",[student.id]);
  expect(await Account.reset(token,'NewPassword123!')).toBeNull();
  await db.none("UPDATE users SET reset_expires_at=NOW()+INTERVAL '30 minutes' WHERE id=$1",[student.id]);
  await anonymous.post('/reset-password/'+token).type('form').send({password:fixtures.password,confirmPassword:fixtures.password}).expect(302);
  expect(await Account.validReset(token)).toBeNull();expect(await Account.reset(token,'AnotherPassword123!')).toBeNull();
  await session.get('/dashboard').expect(302).expect('Location','/login');
});
